  IconShare: ['square_arrow_up'],
  IconPlus: ['plus'],
  IconCheck: ['checkmark'],
  IconClose: ['xmark'],
  IconGear: ['gear_alt'],
  IconQuote: ['quote_bubble', 'quote_bubble_fill'],
  IconQueue: ['list_bullet'],
  IconMusic: ['music_note'],
  IconMusicList: ['music_note_list'],
  IconTrash: ['trash'],
  IconPencil: ['pencil'],
  IconExternal: ['arrow_up_right_square'],
  IconSpeaker: ['speaker_3_fill'],
  IconSpeakerLow: ['speaker_1_fill'],
